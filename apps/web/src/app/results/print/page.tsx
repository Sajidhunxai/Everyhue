"use client";

import { useEffect, useState } from "react";
import type { AnalyzeResult } from "@photomatcher/types";
import { ResultsDisplay } from "@/components/results-display";

export default function PrintResultsPage() {
  const [result, setResult] = useState<AnalyzeResult | null>(null);

  useEffect(() => {
    const raw = sessionStorage.getItem("photomatcher:lastResult");
    if (raw) setResult(JSON.parse(raw) as AnalyzeResult);
  }, []);

  useEffect(() => {
    if (result) {
      const t = setTimeout(() => window.print(), 400);
      return () => clearTimeout(t);
    }
  }, [result]);

  if (!result) return <p>No results to export. Run an analysis first.</p>;

  return (
    <div className="print-page">
      <h1>Every Hue Style Card</h1>
      <h2>{result.seasonLabel}</h2>
      <ResultsDisplay result={result} />
      <p className="muted">Generated by Every Hue</p>
      <style jsx global>{`
        @media print {
          .site-header,
          .actions {
            display: none !important;
          }
        }
        .print-page {
          padding: 1rem;
        }
      `}</style>
    </div>
  );
}
